// Writes demo/icons.js: the Material Design Icons paths the cards and the demo use, so the demo's stand-in <ha-icon>
// can draw them without Home Assistant. Also writes the demo Wi-Fi QR code. Run after adding an icon.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import * as mdi from '@mdi/js';
import QRCode from 'qrcode';

const root = new URL('../', import.meta.url);
const files = ['src/core.js', ...readdirSync(new URL('src/cards/', root)).map((f) => `src/cards/${f}`), 'demo/demo.js'];
// Icons the cards build from parts (`mdi:${…}`), which the scan below can't see.
const names = new Set(['alarm', 'bell-outline']);
for (const f of files) {
  const text = readFileSync(new URL(f, root), 'utf8');
  for (const m of text.matchAll(/mdi:([a-z0-9-]+)/g)) names.add(m[1]);
  for (const m of text.matchAll(/'((?:weather|alert)-[a-z-]+)'/g)) names.add(m[1]);
}
const camel = (n) => `mdi${n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('')}`;
const map = Object.fromEntries([...names].sort().filter((n) => mdi[camel(n)]).map((n) => [n, mdi[camel(n)]]));
writeFileSync(new URL('demo/icons.js', root), `// Generated by scripts/demo-icons.mjs from @mdi/js (Apache-2.0).\nexport default ${JSON.stringify(map, null, 1)};\n`);
writeFileSync(new URL('demo/wifi.svg', root), await QRCode.toString('WIFI:T:WPA;S:Guest network;P:not-a-real-password;;', { type: 'svg', margin: 1 }));
console.log(`demo/icons.js: ${Object.keys(map).length} icons; missing: ${[...names].filter((n) => !map[n]).join(', ') || 'none'}`);
